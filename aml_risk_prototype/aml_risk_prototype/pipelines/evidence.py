
"""Build evidence documents for the AML RAG pipeline."""

import json
from datetime import datetime, timezone

from aml.core import connect


def create_evidence_table(db):
    db.execute("""
        CREATE TABLE IF NOT EXISTS aml_evidence (
            event_id TEXT PRIMARY KEY,
            source TEXT NOT NULL,
            transaction_id TEXT NOT NULL,
            risk_score INTEGER NOT NULL,
            risk_level TEXT NOT NULL,
            alert_status TEXT,
            document_text TEXT NOT NULL,
            metadata_json TEXT NOT NULL,
            updated_at TEXT NOT NULL
        )
    """)


def build_evidence():
    count = 0
    now = datetime.now(timezone.utc).isoformat()

    with connect() as db:
        create_evidence_table(db)

        rows = db.execute("""
            SELECT
                g.event_id,
                g.transaction_id,
                g.source,
                g.customer_id,
                g.amount_usd,
                g.amount_btc,
                g.risk_score,
                g.risk_level,
                g.triggered_rules,
                g.rule_version,
                s.event_time,
                s.ingested_at,
                s.status AS transaction_status,
                s.fee_btc,
                s.is_synthetic,
                a.status AS alert_status,
                a.explanation,
                b.payload
            FROM gold_risk_scores g
            JOIN silver_transactions s
                ON g.event_id = s.event_id
            JOIN bronze b
                ON g.event_id = b.event_id
            LEFT JOIN gold_aml_alerts a
                ON g.event_id = a.event_id
        """).fetchall()

        for row in rows:
            raw = json.loads(row["payload"])
            rules = json.loads(row["triggered_rules"])

            metadata = {
                "event_id": row["event_id"],
                "transaction_id": row["transaction_id"],
                "source": row["source"],
                "risk_score": row["risk_score"],
                "risk_level": row["risk_level"],
                "rule_version": row["rule_version"],
                "rule_ids": [
                    rule["rule"] for rule in rules
                ],
                "is_synthetic": bool(row["is_synthetic"])
            }

            rule_details = (
                "\n".join(
                    f"- {rule['rule']}: "
                    f"{rule['reason']} "
                    f"(+{rule['points']} points)"
                    for rule in rules
                )
                if rules else "No detection rules triggered."
            )

            input_addresses = raw.get(
                "input_addresses", []
            )
            output_addresses = raw.get(
                "output_addresses", []
            )

            document = f"""
AML TRANSACTION INVESTIGATION EVIDENCE

Event ID: {row['event_id']}
Transaction ID: {row['transaction_id']}
Source: {row['source']}
Synthetic data: {bool(row['is_synthetic'])}

Transaction Information:
Event Time: {row['event_time']}
Ingested At: {row['ingested_at']}
Transaction Status: {row['transaction_status']}
Customer ID: {row['customer_id']}
USD Amount: {row['amount_usd']}
Total BTC Outputs: {row['amount_btc']}
BTC Fee: {row['fee_btc']}
Input Addresses: {json.dumps(input_addresses)}
Output Addresses: {json.dumps(output_addresses)}
Input Count: {raw.get('input_count')}
Output Count: {raw.get('output_count')}

Risk Assessment:
Risk Score: {row['risk_score']}/100
Risk Level: {row['risk_level']}
Rule Version: {row['rule_version']}
Triggered Rules:
{rule_details}

AML Review:
Alert Status: {row['alert_status']}
Alert Explanation: {row['explanation']}

Interpretation:
This risk score is generated by prototype detection
rules. It is not a probability of criminal activity
or proof of money laundering. Bitcoin total outputs
may include change outputs.
""".strip()

            db.execute("""
                INSERT INTO aml_evidence (
                    event_id, source, transaction_id,
                    risk_score, risk_level, alert_status,
                    document_text, metadata_json, updated_at
                )
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)

                ON CONFLICT(event_id) DO UPDATE SET
                    source = excluded.source,
                    transaction_id = excluded.transaction_id,
                    risk_score = excluded.risk_score,
                    risk_level = excluded.risk_level,
                    alert_status = excluded.alert_status,
                    document_text = excluded.document_text,
                    metadata_json = excluded.metadata_json,
                    updated_at = excluded.updated_at
            """, (
                row["event_id"],
                row["source"],
                row["transaction_id"],
                row["risk_score"],
                row["risk_level"],
                row["alert_status"],
                document,
                json.dumps(metadata),
                now
            ))

            count += 1

        db.commit()

    print("AML evidence documents created/updated:", count)
    return count


if __name__ == "__main__":
    build_evidence()
